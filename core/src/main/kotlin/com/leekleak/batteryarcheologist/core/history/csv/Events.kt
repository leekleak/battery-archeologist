package com.leekleak.batteryarcheologist.core.history.csv

/**
 * Details contained in one CSV line.
 *
 * Port of Go `csv.Event`. Go's `Start` and `End` fields are named [startMs]
 * and [endMs] here to make the unit explicit; both are epoch milliseconds.
 */
data class Event(
    val type: String = "",
    val startMs: Long = 0L,
    val endMs: Long = 0L,
    val value: String = "",
    val opt: String = "",
    /** For populating from package info. Port of Go `Event.AppName`. */
    val appName: String = "",
)

/**
 * Result of [extractEvents].
 *
 * The Go function returns `(map[string][]Event, []error)`; this groups those
 * two values. [errors] contains the same `record N: ...` messages the Go
 * implementation produces.
 */
data class ExtractEventsResult(
    val events: Map<String, List<Event>>,
    val errors: List<String>,
)

/**
 * Extracts all events matching any of the given metric names.
 *
 * If [metrics] is non-null, the result contains an entry for every requested
 * metric, using an empty list when there are no matching events (Go uses a nil
 * slice). If [metrics] is `null`, all metrics found in the input are returned.
 *
 * Parsing errors are collected in [ExtractEventsResult.errors] and parsing
 * continues with the remaining records. Empty or blank input is reported the
 * same way as upstream (an empty result map plus the
 * `nil result generated by ParseCSV` error), because Go's `ParseCSV` returns a
 * nil slice in that case.
 *
 * Port of Go `csv.ExtractEvents`.
 */
fun extractEvents(
    csvInput: String,
    metrics: List<String>? = null,
): ExtractEventsResult {
    val records = parseCsvRecords(csvInput)
    if (records.isEmpty()) {
        // Go's checkinutil.ParseCSV returns a nil slice for empty/blank input,
        // which ExtractEvents reports as an error before initializing the map.
        return ExtractEventsResult(
            events = emptyMap(),
            errors = listOf("nil result generated by ParseCSV"),
        )
    }
    val events = LinkedHashMap<String, MutableList<Event>>()
    if (metrics != null) {
        for (metric in metrics) {
            events.getOrPut(metric) { mutableListOf() }
        }
    }

    val errors = ArrayList<String>()
    records.forEachIndexed { index, parts ->
        // Skip the CSV header.
        if (parts.isEmpty() || parts.joinToString(",") == Csv.FILE_HEADER) {
            return@forEachIndexed
        }

        val desc = parts[0]
        if (metrics != null && !events.containsKey(desc)) {
            // Ignore non-matching metrics.
            return@forEachIndexed
        }

        val event = try {
            eventFromRecord(parts)
        } catch (e: IllegalArgumentException) {
            errors.add("record $index: ${e.message}")
            return@forEachIndexed
        }
        events.getOrPut(desc) { mutableListOf() }.add(event)
    }

    return ExtractEventsResult(events, errors)
}

/**
 * Merges all overlapping or touching events.
 *
 * Events are sorted by start time first. Overlapping events are collapsed into
 * a single event containing only the overall start and end times (type, value,
 * opt, and app name are dropped for merged intervals, as in the Go code).
 *
 * The Go implementation sorts its input in place; this function leaves the
 * input untouched.
 *
 * Port of Go `csv.MergeEvents`.
 */
fun mergeEvents(events: List<Event>): List<Event> {
    if (events.isEmpty()) return emptyList()

    val sorted = events.sortedBy { it.startMs }
    val result = ArrayList<Event>()
    var previous = sorted.first()
    for (current in sorted.drop(1)) {
        if (previous.endMs < current.startMs) {
            result.add(previous)
            previous = current
        } else {
            previous = Event(
                startMs = previous.startMs,
                endMs = maxOf(previous.endMs, current.endMs),
            )
        }
    }
    result.add(previous)
    return result
}

/**
 * Parses one CSV record in the format
 * `desc,metricType,start,end,value,opt`.
 *
 * @throws IllegalArgumentException with a message matching the Go
 *   implementation's `error` text.
 */
private fun eventFromRecord(parts: List<String>): Event {
    if (parts.size != 6) {
        throw IllegalArgumentException(
            "non matching ${formatGoStringSlice(parts)}, len was ${parts.size}",
        )
    }
    return Event(
        type = parts[1],
        startMs = parseGoInt64(parts[2]),
        endMs = parseGoInt64(parts[3]),
        value = parts[4],
        opt = parts[5],
    )
}

private val DECIMAL_INTEGER = Regex("[+-]?[0-9]+")

/**
 * Parses a base-10 int64 with error messages mirroring Go's `strconv.ParseInt`.
 */
private fun parseGoInt64(value: String): Long {
    if (!DECIMAL_INTEGER.matches(value)) {
        throw IllegalArgumentException(
            "strconv.ParseInt: parsing \"$value\": invalid syntax",
        )
    }
    return value.toLongOrNull()
        ?: throw IllegalArgumentException(
            "strconv.ParseInt: parsing \"$value\": value out of range",
        )
}

/** Formats a list the way Go's `fmt` formats a `[]string`. */
private fun formatGoStringSlice(parts: List<String>): String =
    parts.joinToString(separator = " ", prefix = "[", postfix = "]")
